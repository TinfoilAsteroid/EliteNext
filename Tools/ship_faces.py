"""Face polygons for solid ships (SOLID_HULL, Documentation/SolidHulls.md), made from the ship models.

The models (Data/ships/*.asm, BBC Elite format) have vertices, edges and face normals but no face polygons: a face is
its normal and the edges that name it. For each face this chains its edges (leaving out decoration edges, whose two
faces are the same) into a closed loop of vertices. A model whose faces all close gets a face table, written at the end
of its file between generated markers, and its header's solid fields set:

    DB $00          ; supports solid fill
    DW <Ship>Faces  ; the face table
    DB <Ship>FacesSize

The face table:  DB r (the number of records), then r records:  DW mask, DB n, v0 * 4, v1 * 4, ...
  mask: the faces (bit f = face f) of which any one facing us makes the polygon visible; a face's own record is just
        its bit, in normal order, so record f is face f
  n:    its vertices (0 for a face with no edges), as offsets x4 as the edges store them, which index UBnkNodeArray
then the phase 2 polygons:  DB p, then p records:  DW mask, DB type, n, v0 * 4, ...  (drawn after the hull's faces,
  in this order, unsorted; type: PortEngine or PortEntrance, Data/ShipModelEquates.asm, which picks the colour)
then the lone lines:  DB l, then l lines:  DW mask, DB v0 * 4, v1 * 4  (mask: the edge's two faces, as the wireframe)
A model with a face whose edges don't close keeps $FF (drawn as wireframe) and is reported, to be fixed by hand.

PRUNE (fix A, TODO.md "Solid hulls"): for these models a face's edges that hang off its loop or stand apart from it
(fins, prongs, guns labelled with the faces they sit on) are left out of the face. Each chain of 2 or more such
edges, joined end to end with both ends on the hull, is closed with a straight edge between its ends into a polygon of
its own (a fin), visible when any face its edges are labelled with is; a single such edge stays a line only.

PORTS (phase 2): for these models each closed loop of a face's decoration edges (both faces the same: the engine
ports on the back, later a station's entrance or a ship's view ports) is a filled polygon of its own, drawn after the
hull so it's never painted over, and seen when its face is. The map gives the model's ports' type.

LONE_LINES (fix C): for these models an edge whose two ends are on no other edge (a sensor / gun port line out of the
nose) is left out of the faces and written as a lone line, which SolidHullDraw draws over the fill.

usage: python Tools/ship_faces.py [--check]     --check: write nothing, exit 1 if a file would change
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHIPS = os.path.join(ROOT, "Data", "ships")
NL = chr(10)
CR = chr(13)
BEGIN = "; --- SOLID_HULL face table: generated by Tools/ship_faces.py from the edges above, do not edit ---"
END = "; --- end of generated face table ---"
MAX_TABLE = 255                         # the header's length byte (UBnkHullSolid holds 400)
PRUNE = {"Missile"}                     # fix A plus fins (reviewed models only)
LONE_LINES = {"CobraMk3", "Cobra_Mk_3_P"}   # fix C: nose lines drawn as lines (reviewed models only)
PORTS = {"CobraMk3": "PortEngine", "Cobra_Mk_3_P": "PortEngine",   # phase 2: decoration loops filled after the
         "Coriolis": "PortEntrance", "Dodo": "PortEntrance"}         # hull (engine ports, station entrances)


def nums(code):
    return [int(t[1:], 16) if t.startswith("$") else int(t) for t in re.findall(r"\$[0-9A-Fa-f]+|\b\d+\b", code)]


def block(lines, label, size):
    """the DB bytes from label up to the next label or equ, as records of size bytes. An IFDEF's own branch (such as
    Missile.asm's DEBUGMODEL data) is left out and its ELSE branch kept: the defines are off in the game build"""
    start = next((k for k, l in enumerate(lines) if re.match(rf"^{label}(?!\w)", l)), None)
    if start is None:
        return []
    flat, skip = [], False
    for k in range(start, len(lines)):
        code = lines[k].split(";")[0]
        if k > start and (re.match(r"^\w", code) or "equ" in code.lower()):
            break
        word = code.split()
        if "IFDEF" in word:                             # (also on the label's own line: "MissileVertices: IFDEF ...")
            skip = True
            continue
        if "ELSE" in word or "ENDIF" in word:
            skip = False
            continue
        if not skip and "DB" in code:
            flat += nums(code.split("DB", 1)[1])
    return [flat[i:i + size] for i in range(0, len(flat) - size + 1, size)]


def faces_of(lines, prune=False, lone=False, ports=False):
    """(prefix, vertex count, [(face, loop or None, edges)], [(mask, fin loop)], [(mask, v0, v1)], [(mask, port loop)])
    for a model's lines; with prune, fix A and the fins (see PRUNE above); with lone, the lone lines (LONE_LINES); with
    ports, the phase 2 polygons (PORTS)"""
    prefix = next((m.group(1) for l in lines for m in [re.match(r"^(\w+?)Vertices(?!\w)", l)] if m), None)
    if not prefix:
        return None
    verts, edges, norms = block(lines, prefix + "Vertices", 6), block(lines, prefix + "Edges", 4), block(lines, prefix + "Normals", 4)
    out, stray = [], {}                                 # stray: pruned edge -> its two faces
    deg = {}
    for e in edges:
        for v in (e[2] // 4, e[3] // 4):
            deg[v] = deg.get(v, 0) + 1
    singles = [e for e in edges if lone and deg[e[2] // 4] == 1 and deg[e[3] // 4] == 1]
    lines_out = [(1 << (e[1] >> 4) | 1 << (e[1] & 15), e[2] // 4, e[3] // 4) for e in singles]
    for f in range(len(norms)):
        es = []
        for e in edges:
            f1, f2 = e[1] >> 4, e[1] & 15
            if f1 != f2 and f in (f1, f2) and e not in singles:
                es.append((e[2] // 4, e[3] // 4))
        if prune:
            kept = pruned(es)
            for a, b in set(es) - set(kept):
                e = next(e for e in edges if {e[2] // 4, e[3] // 4} == {a, b})
                stray[(a, b)] = {e[1] >> 4, e[1] & 15}
            es = kept
        out.append((f, loop_of(es) if es else [], es))
    fins = []
    hull = {v for _, loop, _ in out if loop for v in loop}
    for comp in components(list(stray)):
        path = path_of(comp)
        if path and len(comp) >= 2 and (path[0] in hull or path[-1] in hull):
            fins.append((sum(1 << f for f in set().union(*(stray[e] for e in comp))), path))
    late = []
    for f in range(len(norms)) if ports else ():
        deco = [(e[2] // 4, e[3] // 4) for e in edges if e[1] >> 4 == f and e[1] & 15 == f]
        for comp in components(deco):
            loop = loop_of(comp)
            if loop:
                late.append((1 << f, loop))
    return prefix, len(verts), out, fins, lines_out, late


def adjacency(es):
    adj = {}
    for a, b in es:
        adj.setdefault(a, []).append(b)
        adj.setdefault(b, []).append(a)
    return adj


def loop_of(es):
    """the edges' vertices in order round a closed loop, or None if they aren't one"""
    adj = adjacency(es)
    if len(es) < 3 or not all(len(v) == 2 for v in adj.values()):
        return None
    start = es[0][0]
    loop, prev, cur = [], None, start
    while True:
        loop.append(cur)
        nxt = [w for w in adj[cur] if w != prev]
        prev, cur = cur, nxt[0]
        if cur == start or len(loop) > len(adj):
            break
    return loop if len(loop) == len(adj) and cur == start else None


def pruned(es):
    """es without the edges that hang off (an end on no other edge), repeatedly: a loop's spurs and separate chains go"""
    while True:
        deg = {}
        for a, b in es:
            deg[a] = deg.get(a, 0) + 1
            deg[b] = deg.get(b, 0) + 1
        keep = [(a, b) for a, b in es if deg[a] > 1 and deg[b] > 1]
        if len(keep) == len(es):
            return keep
        es = keep


def components(es):
    """the edges in connected groups"""
    left, out = set(es), []
    while left:
        comp, todo = set(), [next(iter(left))]
        while todo:
            e = todo.pop()
            if e in left:
                left.discard(e)
                comp.add(e)
                todo += [g for g in left if set(g) & set(e)]
        out.append(sorted(comp))
    return out


def path_of(es):
    """the vertices end to end if the edges are one simple open chain, else None"""
    adj = adjacency(es)
    ends = [v for v, n in adj.items() if len(n) == 1]
    if len(ends) != 2 or any(len(n) > 2 for n in adj.values()):
        return None
    path, prev, cur = [min(ends)], None, min(ends)
    while len(adj[cur]) > 1 or prev is None:
        nxt = [w for w in adj[cur] if w != prev]
        prev, cur = cur, nxt[0]
        path.append(cur)
    return path if len(path) == len(adj) else None


def generate(path):
    """the file's new text, and (ship, [faces that don't close])"""
    raw = open(path, newline="", encoding="latin-1").read()
    crlf = (CR + NL) in raw
    lines = [l.rstrip() for l in raw.replace(CR + NL, NL).split(NL)]
    if BEGIN in lines:                                  # drop the old generated table
        b, e = lines.index(BEGIN), lines.index(END)
        lines = lines[:b] + lines[e + 1:]
        while lines and lines[-1] == "":
            lines.pop()
        lines.append("")
    name = os.path.basename(path)[:-4]
    r = faces_of(lines, prune=name in PRUNE, lone=name in LONE_LINES, ports=name in PORTS)
    if not r:                                           # (a label written so it can't be found: stop, don't skip it)
        raise SystemExit(f"{name}: no {name}Vertices label found")
    prefix, nverts, faces, fins, lone, late = r
    broken = [f for f, loop, es in faces if es and loop is None]
    ok = not broken and any(loop for f, loop, es in faces)
    head = next((k for k, l in enumerate(lines) if "Supports Solid Fill" in l), None)
    if head is None:
        return None
    ind = re.match(r"^(\s*)", lines[head]).group(1)
    if ok:
        lines[head:head + 3] = [f"{ind}DB $00                              ; Supports Solid Fill = true (Tools/ship_faces.py)",
                                f"{ind}DW {prefix}Faces{' ' * max(1, 31 - len(prefix) - 5)}; face polygons (SOLID_HULL)",
                                f"{ind}DB {prefix}FacesSize{' ' * max(1, 31 - len(prefix) - 9)}; face table length"]
        recs = [(1 << f, loop or [], f"face {f}") for f, loop, es in faces]
        recs += [(mask, loop, f"fin {k}, seen with faces {', '.join(str(f) for f in range(16) if mask >> f & 1)}")
                 for k, (mask, loop) in enumerate(fins)]
        table = [BEGIN, f"{prefix}Faces:          DB {len(recs)}                     ; records: DW visible mask, DB n, n vertices x4"]
        size = 1
        for mask, loop, what in recs:
            size += 3 + len(loop)
            vals = ", ".join(f"${v * 4:02X}" for v in loop)
            table.append(f"                        DW ${mask:04X} : DB {len(loop)}" + (f", {vals}" if vals else "") + f"    ; {what}")
        table.append(f"                        DB {len(late)}                        ; phase 2 polygons, drawn after the hull: DW mask, DB type, n, vertices")
        size += 1
        for mask, loop in late:
            size += 3 + len(loop)
            vals = ", ".join(f"${v * 4:02X}" for v in loop)
            face = next(f for f in range(16) if mask >> f & 1)
            size += 1
            table.append(f"                        DW ${mask:04X} : DB {PORTS[name]}, {len(loop)}, {vals}    ; port on face {face}")
        table.append(f"                        DB {len(lone)}                        ; lone lines: DW visible mask, DB v0, v1 x4")
        for mask, a, b in lone:
            size += 4
            table.append(f"                        DW ${mask:04X} : DB ${a * 4:02X}, ${b * 4:02X}    ; lone line {a}-{b}")
        size += 1
        table += [f"{prefix}FacesSize{' ' * max(1, 15 - len(prefix))}equ $ - {prefix}Faces", END]
        assert size <= MAX_TABLE, f"{prefix}: face table {size} bytes, the header's length byte holds {MAX_TABLE}"
        lines = lines + table + [""]
    else:
        why = f"faces {', '.join(map(str, broken))} don't close" if broken else "no faces"
        lines[head:head + 3] = [f"{ind}DB $FF                              ; Supports Solid Fill = false ({why}: wireframe)",
                                f"{ind}DW $0000                            ; no solid data",
                                f"{ind}DB $00                              ; no solid data"]
    text = NL.join(lines)
    if crlf:
        text = text.replace(NL, CR + NL)
    return text, (name, broken, ok, len(fins), len(lone), len(late))


def main():
    check = "--check" in sys.argv
    changed, report = [], []
    for path in sorted(glob.glob(os.path.join(SHIPS, "*.asm"))):
        r = generate(path)
        if not r:
            continue
        text, info = r
        report.append(info)
        old = open(path, newline="", encoding="latin-1").read()
        if text != old:
            changed.append(os.path.basename(path))
            if not check:
                open(path, "w", newline="", encoding="latin-1").write(text)
    solid = [n for n, b, ok, fins, lone, late in report if ok]
    print(f"{len(solid)} of {len(report)} models have face tables")
    for n, b, ok, fins, lone, late in report:
        if b:
            print(f"  wireframe: {n}, faces {b} don't close")
        if fins:
            print(f"  {n}: pruned (fix A), {fins} fins")
        if lone:
            print(f"  {n}: {lone} lone line{'s' * (lone > 1)} (fix C)")
        if late:
            print(f"  {n}: {late} phase 2 port polygon{'s' * (late > 1)}")
    if check and changed:
        print("would change:", ", ".join(changed))
        sys.exit(1)


if __name__ == "__main__":
    main()
